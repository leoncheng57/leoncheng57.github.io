function slugify(title: string): string {
  return title
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '')
}

export const books: Book[] = catalog.map(([title, author, year], index) => {
  const [color, accent] = palette[index % palette.length]
  return { id: slugify(title), title, author, year, color, accent }
})
